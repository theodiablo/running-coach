// Regenerates src/utils/timezoneCountries.ts from the system tz database (zone.tab + tzdata.zi links).
// Usage: node scripts/gen-timezone-countries.mjs [/usr/share/zoneinfo]
import { readFileSync, writeFileSync } from "node:fs";

const dir = process.argv[2] || "/usr/share/zoneinfo";
const version = readFileSync(`${dir}/tzdata.zi`, "utf8").match(/^# version (\S+)/m)?.[1] ?? "unknown";
const zoneCountry = new Map();
for (const line of readFileSync(`${dir}/zone.tab`, "utf8").split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [cc, , zone] = line.split("\t");
  zoneCountry.set(zone, cc);
}
for (const line of readFileSync(`${dir}/tzdata.zi`, "utf8").split("\n")) {
  const [kind, target, alias] = line.split(" ");
  if (kind !== "L" || zoneCountry.has(alias) || alias.startsWith("Etc/")) continue;
  if (zoneCountry.has(target)) zoneCountry.set(alias, zoneCountry.get(target));
}
const byCountry = {};
for (const [zone, cc] of [...zoneCountry].sort()) (byCountry[cc] ??= []).push(zone);
const rows = Object.keys(byCountry).sort().map(cc => `  ${cc}: "${byCountry[cc].join(" ")}",`);
writeFileSync("src/utils/timezoneCountries.ts", `// Generated by scripts/gen-timezone-countries.mjs from tzdata ${version}; do not edit by hand.
// The IANA time zones (and their legacy aliases) of each country.
export const TIMEZONES_BY_COUNTRY: Record<string, string> = {
${rows.join("\n")}
};
`);
console.log(`tzdata ${version}: ${zoneCountry.size} zones, ${rows.length} countries`);
